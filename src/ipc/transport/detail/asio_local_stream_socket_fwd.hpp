/**
 * Our transport::asio_local_stream_socket utilities support transmitting at most this many native handles (FDs)
 * per single-message OS-call or batch-transmission per-message slot.
 *
 * ### Rationale: Current value ###
 * It is 1.  transport::asio_local_stream_socket utilities, while themselves opportunistically public, exist
 * in the first place to support sync_io::Native_socket_stream and derivative(s) which, formally speaking,
 * themselves implement concepts sync_io::Native_handle_sender and sync_io::Native_handle_receiver.  Those
 * APIs as of this writing permit at most 1 `Native_handle` to be transmitted per message.
 *
 * That could all change at some point; but for now this straightforwardly need only be 1.
 */
constexpr size_t N_PAYLOAD_FDS = 1;

