/**
 * Returns an #Endpoint corresponding to the given absolute Shared_name, so that an #Acceptor or #Peer_socket could
 * be bound to it.  TRACE logging possible; WARNING on error.
 *
 * @param logger_ptr
 *        Logger to use for subsequently logging.
 * @param absolute_name
 *        Name.
 * @param err_code
 *        See `flow::Error_code` docs for error reporting semantics.  #Error_code generated:
 *        one(s) generated by boost.asio; as of this writing at least:
 *        `boost::asio::error::name_too_long` (self-explanatory).
 * @return If it did not throw (which cannot happen if `err_code` non-null): default-cted `Endpoint` on error
 *         (if and only if `*err_code` truthy); the actual `Endpoint` otherwise (on success).
 * @tparam Protocol
 *         At least, `Protocol_byte_stream` or `Protocol_pkt_stream`.
 */
template<typename Protocol>
Endpoint<Protocol> endpoint_at_shared_name(flow::log::Logger* logger_ptr,
                                           const Shared_name& absolute_name, Error_code* err_code = nullptr);

